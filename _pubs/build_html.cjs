const fs = require("node:fs");
const path = require("node:path");
const { JSDOM } = require("jsdom");
const createPublications = require("../assets/js/publications.js");

const repo = path.resolve(__dirname, "..");
const data = JSON.parse(fs.readFileSync(path.join(repo, "assets/publications.json"), "utf8"));
const dom = new JSDOM("<!doctype html><div id=\"pubs\"></div>");
const root = dom.window.document.getElementById("pubs");
createPublications(dom.window.document).build(root, data);
// Keep bibliography text from being interpreted as Liquid when Jekyll includes it.
const html = root.innerHTML.replace(/\{/g, "&#123;").replace(/\}/g, "&#125;");
const output = path.join(repo, "_includes/publications.generated.html");
fs.writeFileSync(output, "<!-- Generated by _pubs/build_html.cjs; do not edit. -->\n" + html + "\n");
console.log(`Wrote ${path.relative(repo, output)}: ${root.querySelectorAll(".pub-row").length} publications.`);
dom.window.close();
